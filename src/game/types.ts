export interface Vec {
  x: number;
  y: number;
}

export interface Rect {
  x: number;
  y: number;
  w: number;
  h: number;
}

/** Растаптываются все, кроме "call" - некоторые вещи прыжком не решаются. */
/**
 * Кто мешает жить.
 *
 * legacy - коробка наследства, топчется.
 * bug    - жук, быстрый и мелкий, топчется.
 * call   - окно созвона, парит и НЕ топчется: только обойти или тестом.
 * debt   - техдолг: большой, медленный, с одного раза не убирается.
 * hr     - рекрутёр: летает волной и сам подтягивается к игроку.
 */
export type FoeKind = "legacy" | "bug" | "call" | "debt" | "hr";

export interface FoeSpec {
  kind: FoeKind;
  /** Стартовая позиция по X. */
  x: number;
  /** Уровень пола, на котором стоит враг (для "call" - высота парения). */
  baseY: number;
  /** Границы патрулирования. */
  min: number;
  max: number;
}

/**
 * Оформление уровня.
 *
 * surface     - день: небо, холмы, офисные башни на горизонте.
 * underground - подземелье: потолок вместо неба, теснота вместо простора.
 * night       - ночная смена: тёмное небо, звёзды, и в башнях горит
 *               заметно больше окон, чем днём.
 * prod        - прод горит: аварийное красное освещение, пульсирующее
 *               в такт мигалке. Читается тревогой с первого кадра.
 *
 * castle      - замок мира, где ждёт мини-босс: каменный свод, как под
 *               землёй, и красное зарево снизу. Узнаётся с первого кадра:
 *               раз стены серые - впереди собес.
 * sky         - небо: ни башен, ни холмов, только облака. Земля здесь
 *               редкость, дорога идёт по лифтам и балкам над пропастью.
 *
 * Тема - это не только цвет: у подземелья свой потолок, у ночи звёзды,
 * у аварии пульс. Ради одной перекраски отдельную тему заводить было бы
 * незачем, а вот ради смены ощущения - стоит.
 */
export type Theme = "surface" | "underground" | "night" | "prod" | "castle" | "sky";

/**
 * Мини-босс замка. Идёт на игрока, прыгает и кидает вопросы; пока он
 * жив, дверь заперта. Боссов четыре, по одному на мир, и отличаются они
 * числами, а не кодом: тестовое задание не кидается вовсе, финальный
 * собес кидается чаще всех.
 */
export interface Boss {
  /** Подпись над головой: с кем именно дерёмся. */
  name: string;
  /** Сколько попаданий держит - от этого же растёт злость по ходу боя. */
  maxHp: number;
  /** Шаг в сторону игрока на полном здоровье. */
  pace: number;
  /** Кадры между вопросами на полном здоровье. 0 - не кидается. */
  throwEvery: number;
  /** Кадры между прыжками на полном здоровье. */
  hopEvery: number;
  x: number;
  y: number;
  w: number;
  h: number;
  /** Пол арены - высота, на которую он приземляется. */
  baseY: number;
  /** Границы арены: за них не выходит, чтобы бой не расползался. */
  min: number;
  max: number;
  dir: 1 | -1;
  vy: number;
  hp: number;
  /** Кадры неуязвимости и мигания после попадания. */
  hit: number;
  /**
   * Кадры отхода после того, как босс задел игрока. Без него он просто
   * упирается в игрока и бьёт его снова и снова: отбрасывание контакт
   * не разрывает, потому что босс тут же догоняет. Выбраться нельзя.
   */
  recoil: number;
  /** Обратный отсчёт до следующего вопроса. */
  cool: number;
  /** Обратный отсчёт до следующего прыжка. */
  hop: number;
  /** Кадры агонии; после них босс исчезает и дверь открывается. */
  dying: number;
}

export interface LevelSpec {
  name: string;
  /** Мир с нуля: 0 Джун, 1 Мидл, 2 Сеньор, 3 Лид. */
  world: number;
  /** Место в мире с нуля: открытый уровень, подземелье или небо, замок. */
  stage: number;
  /**
   * Норма времени в секундах. Считается из длины карты и скорости, а не
   * одна на всех: короткий первый мир и длинный последний с одной нормой
   * давали то звезду даром, то невозможную.
   */
  par: number;
  theme: Theme;
  /** Подпись на заставке: чем этот уровень отличается от предыдущего. */
  mood?: string;
  /** Грейд определяет темп: уровень = ступень карьеры. */
  grade: string;
  width: number;
  groundY: number;
  /** Предельная скорость игрока. Растёт с грейдом. */
  maxSpeed: number;
  /** Цвет дальних холмов - задаёт настроение уровня. */
  tint: string;
  platforms: Rect[];
  foes: FoeSpec[];
  gems: Vec[];
  coffee: Vec[];
  /** Прод: коснулся - минус жизнь. */
  hazards: Rect[];
  /** Болото легаси: скорость и прыжок вдвое хуже. */
  swamps: Rect[];
  blocks: BlockSpec[];
  moving: MovingSpec[];
  pipes: Pipe[];
  rotors: RotorSpec[];
  /**
   * Флагшток оффера перед дверью. Чем выше зацепился, тем больше бонус -
   * ради верхушки уровень переигрывают, и время на карте перестаёт быть
   * просто цифрой.
   */
  pole: Vec;
  /** Скорость стены дедлайна в px/кадр. 0 - стены нет. */
  deadlineSpeed: number;
  /** Коммиты: пройденный чекпоинт становится точкой возрождения. */
  checkpoints: Vec[];
  door: Vec;
  /** Мини-босс - только в замке, на третьем уровне мира. */
  boss: Boss | null;
}

/**
 * Фазы забега.
 *
 * intro   - заставка уровня: имя, грейд, жизни. Пауза на вдох перед стартом.
 * signing - финиш: спуск по флагштоку и проход в дверь. Уровень уже пройден,
 *           но управление отдано анимации, а не игроку.
 */
export type Phase = "intro" | "play" | "signing" | "clear" | "over" | "final";

/**
 * Грейд игрока - это запас прочности, как размер в платформерах.
 * Урон откатывает на ступень вниз, а не убивает сразу.
 *
 * Хитбокс при этом НЕ меняется: крупный персонаж не пролез бы под
 * платформами на y=46 при земле на y=62 - там 16 пикселей, и игра
 * встала бы намертво. Растёт только вид.
 */
export type Grade = 0 | 1 | 2;

export const GRADE_NAMES = ["ДЖУН", "МИДЛ", "СЕНЬОР"] as const;

/**
 * Что лежит в блоке с вопросом. Аналоги классических бонусов, но свои:
 *
 *  offer   - оффер, поднимает грейд джун -> мидл
 *  tests   - тесты, поднимают до сеньора и дают чем отбиваться:
 *            тесты убивают баги, это и правда жизни, и механика
 *  coffee  - ускорение
 *  vacation - отпуск: временная неуязвимость, на отдыхе ничто не достанет
 *  life    - лишняя жизнь. Лежит только в невидимых ящиках: её находят,
 *            а не получают по дороге
 */
export type BlockDrop = "offer" | "tests" | "coffee" | "vacation" | "life";

/**
 * question - ящик с вопросом, внутри предмет.
 * brick    - кирпич: сеньор его ломает, остальные бьются головой.
 * coins    - кирпич-заначка: снаружи обычный кирпич, а на каждый удар
 *            снизу отдаёт по скиллу, пока не опустеет. Сеньор его не
 *            ломает - иначе заначка сгорала бы с первого удара.
 */
export type BlockKind = "question" | "brick" | "coins";

export interface BlockSpec {
  kind: BlockKind;
  x: number;
  y: number;
  drop?: BlockDrop;
  /**
   * Невидимый ящик. Его не видно и сквозь него проходят, пока не ударишь
   * снизу: тогда он проявляется и отдаёт предмет. Классический секрет
   * жанра - спрятанная жизнь там, где все и так прыгают.
   */
  hidden?: boolean;
}

export interface Block extends BlockSpec {
  /** Кадры анимации подскока после удара снизу. */
  bump: number;
  used: boolean;
  broken: boolean;
  /** Сколько скиллов ещё осталось в кирпиче-заначке. */
  coins: number;
}

/**
 * Предмет, выскочивший из блока.
 *
 * Оффер и отпуск после выезда уходят своим ходом: падают, идут по земле,
 * разворачиваются о стены. Их надо догонять - в этом половина смысла,
 * иначе бонус превращается в кнопку «взять». Тесты и кофе остаются
 * на крыше блока: не всё в мире обязано убегать.
 */
export interface Item {
  kind: BlockDrop;
  x: number;
  y: number;
  vx: number;
  vy: number;
  /** Кадры выезда из блока; пока идут, предмет ещё не живёт своей жизнью. */
  rise: number;
  taken: boolean;
}

export interface Foe {
  kind: FoeKind;
  x: number;
  y: number;
  baseY: number;
  min: number;
  max: number;
  dir: 1 | -1;
  speed: number;
  w: number;
  h: number;
  /** 0 - жив, дальше счётчик кадров анимации сплющивания. */
  squashed: number;
  /**
   * Сколько ещё раз надо прыгнуть сверху. У всех 1, у техдолга 2:
   * технический долг с одного наскока не убирается.
   */
  hp: number;
}

export interface Pickup extends Vec {
  taken: boolean;
}

/**
 * Всплывающая надпись над местом события: «+400», «1UP».
 *
 * Без неё очки меняются молча в шапке, куда во время прыжка никто не смотрит,
 * и связь «сделал - получил» не читается вовсе.
 */
export interface Popup {
  x: number;
  y: number;
  text: string;
  color: string;
  life: number;
}

/**
 * Ротация: цепочка алертов, крутящаяся вокруг стойки. Жанровая классика -
 * препятствие, которое нельзя убить, только выждать. Нижняя точка держится
 * выше роста игрока: ротация стережёт верхнюю дорогу с наградой, а не
 * перекрывает единственный проход по земле.
 */
export interface RotorSpec {
  /** Ось вращения. */
  x: number;
  y: number;
  /** Сколько звеньев в цепочке. Длина - beads * ROTOR_STEP. */
  beads: number;
  /** Радиан за кадр. Знак задаёт сторону вращения. */
  speed: number;
  /** Начальный угол: соседние ротации не должны крутиться в такт. */
  phase: number;
}

export interface Rotor extends RotorSpec {
  angle: number;
}

export interface Particle {
  x: number;
  y: number;
  vx: number;
  vy: number;
  life: number;
  color: string;
}

export interface Player {
  x: number;
  y: number;
  w: number;
  h: number;
  vx: number;
  vy: number;
  onGround: boolean;
  face: 1 | -1;
  /** Кадры, в которые ещё засчитается прыжок после схода с платформы. */
  coyote: number;
  /** Кадры, в которые ещё сработает заранее нажатый прыжок. */
  buffer: number;
  /** Неуязвимость и мигание после урона. */
  hurt: number;
  /** Остаток ускорения от кофе. */
  boost: number;
  /** Текущая ступень: 0 джун, 1 мидл, 2 сеньор. */
  grade: Grade;
  /** Остаток неуязвимости от отпуска. */
  vacation: number;
  /** Задержка между бросками тестов. */
  cooldown: number;
}

/** Брошенный тест: летит, отскакивает от земли, убивает баги. */
export interface Projectile {
  x: number;
  y: number;
  vx: number;
  vy: number;
  life: number;
}

/**
 * Платформа, которая ходит между двумя точками.
 * Игрок на ней едет вместе с ней - иначе она уезжает из-под ног.
 */
export interface MovingPlatform {
  x: number;
  y: number;
  w: number;
  h: number;
  /** Границы хода по выбранной оси. */
  from: number;
  to: number;
  axis: "x" | "y";
  speed: number;
  dir: 1 | -1;
}

export interface MovingSpec {
  x: number;
  y: number;
  w: number;
  axis: "x" | "y";
  /** Насколько далеко уходит от начальной точки. */
  span: number;
  speed: number;
}

/**
 * Труба. Обычная - просто препятствие, на которое запрыгивают.
 * Со ссылкой - вход: встал сверху, нажал вниз, вышел из парной трубы
 * дальше по уровню. Отдельные бонусные комнаты потребовали бы второго
 * состояния мира ради одной механики; парная труба даёт то же ощущение
 * секрета, оставаясь частью того же уровня.
 */
export interface Pipe {
  x: number;
  y: number;
  w: number;
  h: number;
  /** X парной трубы, из которой игрок выйдет. */
  link?: number;
  /**
   * Вход в бонусную комнату: спустился - оказался в отдельном помещении
   * со скиллами и таймером. Одна комната на трубу за забег: иначе в неё
   * можно ходить по кругу и набивать жизни бесконечно.
   */
  bonus?: boolean;
  /** Обратная труба внутри комнаты. */
  exit?: boolean;
}

/** Пишется на сервер вместе со счётом - по нему отсекается накрутка. */
export interface RunStats {
  score: number;
  skills: number;
  levelsCleared: number;
  frames: number;
  jumps: number;
  stomps: number;
  deaths: number;
  /** Сколько блоков разбито - идёт в счёт и в отсечку накрутки. */
  blocks: number;
  /** Врагов убито брошенными тестами. */
  tested: number;
  /** Сколько раз игрок нашёл проход по трубе. */
  pipes: number;
  /** Самая длинная цепочка растоптанных без касания земли. */
  maxCombo: number;
  /** С какого уровня начат забег. Больше нуля - забег с продолжения. */
  startLevel: number;
}
